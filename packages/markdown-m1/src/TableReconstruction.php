<?php
declare(strict_types=1);
namespace OzekiResilience\M1;
if (!defined('ABSPATH')) exit;

/** Read archived materials, emit ordinary import inputs; never write destination internals. */
final class TableReconstruction {
    private static function object(string $raw): array {
        $value=json_decode($raw,true,512,JSON_THROW_ON_ERROR);
        if(!is_array($value))throw new \RuntimeException('Expected JSON structure');
        return $value;
    }
    public static function plan(array $manifest,array $files): array {
        $data=self::object($files['content.json']);
        if(($data['update_contract']??'')!==UpdateContract::SCHEMA||!empty($manifest['legacy_incomplete_article_conditions']))throw new \RuntimeException('Complete publication conditions required');
        $out=['schema'=>'owr-normal-tablepress-registration-1','source_url'=>$manifest['source_url'],'through'=>$manifest['through'],'tables'=>[],'pages'=>[],'held'=>[], 'excluded'=>[], 'destination_owned'=>['TablePress global settings','table registry and allocated IDs','author and last editor generated by ordinary registration']];
        $posts=[];$meta=[];
        foreach($data['tables']['posts'] as $p)$posts[(int)$p['ID']]=$p;
        foreach($data['tables']['postmeta'] as $m)$meta[(int)$m['post_id']][$m['meta_key']]=$m['meta_value'];
        $registry=self::object($data['options']['tablepress_tables']??'{}');
        if(!isset($registry['table_post'])||!is_array($registry['table_post']))throw new \RuntimeException('TablePress source registry missing');
        foreach($registry['table_post'] as $id=>$pid){
            try {
                $p=$posts[(int)$pid]??null;$m=$meta[(int)$pid]??[];
                if(!$p||$p['post_type']!=='tablepress_table')throw new \RuntimeException('Table material missing');
                foreach(['_tablepress_table_options','_tablepress_table_visibility'] as $key)if(!isset($m[$key]))throw new \RuntimeException('Table options or visibility missing');
                $out['tables'][]=['origin_id'=>(string)$id,'table'=>['name'=>$p['post_title'],'description'=>$p['post_excerpt'],'data'=>self::object($p['post_content']),'options'=>self::object($m['_tablepress_table_options']),'visibility'=>self::object($m['_tablepress_table_visibility'])]];
            }catch(\Throwable $e){$out['held']['table:'.$id]=$e->getMessage();}
        }
        foreach($posts as $id=>$p){
            if(!in_array($p['post_type'],['post','page'],true))continue;
            $candidate=html_entity_decode($p['post_content'],ENT_QUOTES|ENT_HTML5,'UTF-8');
            if(!str_contains($candidate,'[table'))continue;
            if(!in_array($p['post_status'],['publish','private'],true)){$out['excluded']['page:'.$id]='Not a formal current publication';continue;}
            if(isset($data['membership'])||in_array((string)($meta[$id]['_wpmem_block']??''),['1','2'],true)||$p['post_parent']){$out['held']['page:'.$id]='Membership or parent mapping needs the combined registration stage';continue;}
            $out['pages'][]=['origin_id'=>$id,'type'=>$p['post_type'],'title'=>$p['post_title'],'slug'=>$p['post_name'],'content'=>$p['post_content'],'status'=>$p['post_status'],'password'=>$p['post_password'],'excerpt'=>$p['post_excerpt'],'date'=>$p['post_date'],'date_gmt'=>$p['post_date_gmt'],'author_origin'=>(int)$p['post_author'],'comment_status'=>$p['comment_status'],'ping_status'=>$p['ping_status']];
        }
        return $out;
    }
}
